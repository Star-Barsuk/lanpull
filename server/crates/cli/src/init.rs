//! `lanpull init` — create the configuration and state for this machine.
//!
//! The command derives the LAN address from the routing table, prompts for the
//! remaining values, creates the share and state directories, and writes the
//! configuration file. When the target is the canonical `/etc/lanpull`, the
//! directory and file are given the operator-readable ownership the service
//! needs (group taken from `$SUDO_GID`).

use std::net::IpAddr;
use std::os::unix::fs::PermissionsExt as _;
use std::path::{Path, PathBuf};

use lanpull_core::config as core_config;
use lanpull_core::error::{Error, Result};
use lanpull_core::ignore::IGNORE_FILE_NAME;

use crate::cli::share::InitArgs;
use crate::cli::Outcome;

/// Run `lanpull init`.
pub fn run(config_path: &Path, args: &InitArgs) -> Result<Outcome> {
    use std::fmt::Write as _;

    let config_dir = config_path.parent().unwrap_or_else(|| Path::new("."));
    let canonical = config_dir == Path::new(core_config::DEFAULT_CONFIG_DIR);

    // The canonical configuration needs root: it is created root-owned with the
    // operator group. Refuse before touching the filesystem so a normal user
    // gets an actionable message instead of a raw permission error. A dry run
    // writes nothing and may run as anyone.
    if !args.dry_run && canonical && effective_uid() != 0 {
        return Err(Error::Usage(format!(
            "{} needs root; run 'sudo lanpull init'",
            config_dir.display()
        )));
    }

    let shares = resolve_shares(&args.shares, canonical)?;
    let state_dir = args
        .state_dir
        .clone()
        .unwrap_or_else(|| PathBuf::from(core_config::DEFAULT_STATE_DIR));
    let bind = args
        .bind
        .clone()
        .unwrap_or_else(|| core_config::DEFAULT_BIND.to_string());
    let port = args.port.unwrap_or(core_config::DEFAULT_PORT);
    let server_ip = match &args.server_ip {
        Some(value) => value
            .parse::<IpAddr>()
            .map_err(|e| Error::Config(format!("SERVER_IP: {e}")))?,
        None => detect_server_ip()?,
    };

    if config_path.exists() && !args.force {
        return Err(Error::Usage(format!(
            "{} already exists; pass --force to overwrite",
            config_path.display()
        )));
    }

    if args.dry_run {
        return Ok(describe(
            config_path,
            &shares,
            &state_dir,
            &bind,
            port,
            server_ip,
            true,
        ));
    }

    std::fs::create_dir_all(config_dir)?;
    // A share created under `sudo` must belong to the operator, who is the one
    // who writes the files and runs the service; a root-owned 0755 directory
    // would leave the documented workflow unwritable.
    for (_, dir) in &shares {
        if !dir.is_dir() {
            std::fs::create_dir_all(dir)?;
            adopt_created_dir(dir)?;
        }
    }
    for (_, dir) in &shares {
        ensure_share_ignore(dir)?;
    }
    create_state_dir(&state_dir)?;

    let mut text = String::new();
    text.push_str("# lanpull server configuration.\n");
    text.push_str("# Generated by 'lanpull init'. Not committed.\n\n");
    for (name, dir) in &shares {
        let _ = writeln!(text, "SHARE_{name}={}", dir.display());
    }
    let _ = writeln!(text, "STATE_DIR={}", state_dir.display());
    let _ = writeln!(text, "BIND={bind}");
    let _ = writeln!(text, "PORT={port}");
    let _ = writeln!(text, "SERVER_IP={server_ip}");
    let _ = writeln!(
        text,
        "CERT_PATH={}",
        state_dir.join(core_config::CERT_FILE_NAME).display()
    );
    let _ = writeln!(
        text,
        "KEY_PATH={}",
        state_dir.join(core_config::KEY_FILE_NAME).display()
    );
    text.push_str("CLIENTS_PATH=lanpull.clients\n");
    text.push_str("ACCESS_PATH=lanpull.access.json\n");
    text.push_str("NETWORKS_PATH=lanpull.networks.json\n");
    let _ = writeln!(text, "AUDIT_LOG={}", state_dir.join("access.log").display());

    lanpull_core::atomic::write_private(config_path, text.as_bytes())?;
    harden_canonical(config_dir, config_path)?;
    // Validate before reporting success.
    core_config::Config::load(config_path)?;

    Ok(describe(
        config_path,
        &shares,
        &state_dir,
        &bind,
        port,
        server_ip,
        false,
    ))
}

/// One share in the `init` payload.
#[derive(Debug, serde::Serialize)]
struct ShareSpec {
    name: String,
    dir: PathBuf,
}

/// `init` payload.
#[derive(Debug, serde::Serialize)]
struct InitData {
    path: PathBuf,
    state_dir: PathBuf,
    bind: String,
    port: u16,
    server_ip: String,
    shares: Vec<ShareSpec>,
    dry_run: bool,
}

/// Build the `init` result, whether it wrote anything or only described it.
fn describe(
    config_path: &Path,
    shares: &[(String, PathBuf)],
    state_dir: &Path,
    bind: &str,
    port: u16,
    server_ip: IpAddr,
    dry_run: bool,
) -> Outcome {
    let mut outcome = Outcome::new().line(if dry_run {
        format!("would write {}", config_path.display())
    } else {
        format!("wrote {}", config_path.display())
    });
    for (name, dir) in shares {
        outcome = outcome.line(format!("  SHARE_{name}={}", dir.display()));
    }
    outcome = outcome
        .line(format!("  STATE_DIR={}", state_dir.display()))
        .line(format!("  BIND={bind}"))
        .line(format!("  PORT={port}"))
        .line(format!("  SERVER_IP={server_ip}"))
        .line("next: lanpull cert, then lanpull access and lanpull account add");
    let shares_json: Vec<ShareSpec> = shares
        .iter()
        .map(|(name, dir)| ShareSpec {
            name: name.clone(),
            dir: dir.clone(),
        })
        .collect();
    let _ = outcome.set_data(&InitData {
        path: config_path.to_path_buf(),
        state_dir: state_dir.to_path_buf(),
        bind: bind.to_string(),
        port,
        server_ip: server_ip.to_string(),
        shares: shares_json,
        dry_run,
    });
    outcome
}

/// The template written to a share's `.lanpullignore` when it is absent.
const IGNORE_TEMPLATE: &str = "\
# lanpull ignore rules for this share, one pattern per line.
# Read by 'lanpull share rescan'; matching files are never distributed.
# lanpull already ignores common build, cache, version-control, and editor
# artifacts; the rules below add to that set, and '!' re-includes a path the
# defaults ignored. A pattern that names a directory also ignores its contents.
# '#' starts a comment; '*' matches within a path segment and '**' across
# segments; a pattern without '/' matches its name at any depth. Lock and
# partial files always stay ignored and cannot be re-included.
#
# Examples:
#   *.iso
#   drafts/**
#   !build/keep.txt
";

/// Give a just-created share directory to the invoking user when run as root.
///
/// `sudo lanpull init` creates the default share before the operator can; the
/// operator (not root) owns the content and runs the service, so the directory
/// is handed over via `$SUDO_UID`/`$SUDO_GID`. Without those variables (for
/// example `sudo -i`), the directory stays root-owned and the warning says what
/// to do about it.
fn adopt_created_dir(path: &Path) -> Result<()> {
    if effective_uid() != 0 {
        return Ok(());
    }
    let uid = std::env::var("SUDO_UID")
        .ok()
        .and_then(|value| value.parse::<u32>().ok());
    let gid = std::env::var("SUDO_GID")
        .ok()
        .and_then(|value| value.parse::<u32>().ok());
    if let (Some(uid), Some(gid)) = (uid, gid) {
        std::os::unix::fs::chown(path, Some(uid), Some(gid))?;
    } else {
        tracing::warn!(
            path = %path.display(),
            "share created as root and $SUDO_UID is unset; chown it to the operator before use"
        );
    }
    Ok(())
}

/// Create `<dir>/.lanpullignore` if it is absent, owned like the share
/// directory.
///
/// The file is an operator-editable control: an existing file is never
/// overwritten. When running as root (a canonical `init`), the new file is
/// given the share directory's owner and group so the operator can edit it.
pub fn ensure_share_ignore(dir: &Path) -> Result<()> {
    use std::os::unix::fs::MetadataExt as _;

    let path = dir.join(IGNORE_FILE_NAME);
    if path.exists() {
        return Ok(());
    }
    std::fs::write(&path, IGNORE_TEMPLATE)?;
    if effective_uid() == 0 {
        let meta = std::fs::metadata(dir)?;
        std::os::unix::fs::chown(&path, Some(meta.uid()), Some(meta.gid()))?;
    }
    Ok(())
}

/// Give a canonical configuration the ownership the service needs.
///
/// `/etc/lanpull` becomes `root:<group>` mode `0770` and the file
/// `root:<group>` mode `0640`, where `<group>` comes from `$SUDO_GID` when the
/// command ran under `sudo`. Outside `/etc/lanpull` nothing changes. The caller
/// has already ensured the canonical path is only written as root.
fn harden_canonical(config_dir: &Path, config_path: &Path) -> Result<()> {
    if config_dir != Path::new(core_config::DEFAULT_CONFIG_DIR) {
        return Ok(());
    }
    let group = std::env::var("SUDO_GID")
        .ok()
        .and_then(|value| value.parse::<u32>().ok());
    std::fs::set_permissions(config_dir, std::fs::Permissions::from_mode(0o770))?;
    std::fs::set_permissions(config_path, std::fs::Permissions::from_mode(0o640))?;
    if let Some(gid) = group {
        std::os::unix::fs::chown(config_dir, Some(0), Some(gid))?;
        std::os::unix::fs::chown(config_path, Some(0), Some(gid))?;
    }
    Ok(())
}

/// The process's effective UID, read from `/proc/self/status`.
pub fn effective_uid() -> u32 {
    let Ok(status) = std::fs::read_to_string("/proc/self/status") else {
        return u32::MAX;
    };
    for line in status.lines() {
        if let Some(rest) = line.strip_prefix("Uid:") {
            if let Some(effective) = rest.split_whitespace().nth(1) {
                if let Ok(uid) = effective.parse::<u32>() {
                    return uid;
                }
            }
        }
    }
    u32::MAX
}

/// Parse `name=path` share specifications, defaulting to a single `default`.
///
/// The canonical configuration defaults to `/srv/lanpull/share` (the documented
/// layout); a development configuration defaults to `$HOME/lanpull-share` so it
/// can be created without root.
fn resolve_shares(specs: &[String], canonical: bool) -> Result<Vec<(String, PathBuf)>> {
    if specs.is_empty() {
        let default = if canonical {
            PathBuf::from("/srv/lanpull/share")
        } else {
            let home = std::env::var("HOME").unwrap_or_else(|_| "/home".to_string());
            PathBuf::from(home).join("lanpull-share")
        };
        return Ok(vec![("default".to_string(), default)]);
    }
    let mut shares = Vec::new();
    for spec in specs {
        let (name, path) = spec
            .split_once('=')
            .ok_or_else(|| Error::Usage(format!("invalid --share {spec}: expected name=path")))?;
        if !core_config::valid_share_name(name) {
            return Err(Error::Usage(format!(
                "invalid share name {name}: must match {}",
                core_config::SHARE_NAME_PATTERN
            )));
        }
        shares.push((name.to_string(), PathBuf::from(path)));
    }
    Ok(shares)
}

/// Create the state directory when this user may; otherwise defer to install.
///
/// `lanpull init` may run as the operator before `make install`, and the
/// default `/var/lib/lanpull` needs root. A permission failure is not fatal
/// here: the install script creates the directory with the right owner and
/// mode.
fn create_state_dir(state_dir: &Path) -> Result<()> {
    if state_dir.is_dir() {
        return Ok(());
    }
    match std::fs::create_dir_all(state_dir) {
        Ok(()) => {
            std::fs::set_permissions(state_dir, std::fs::Permissions::from_mode(0o700))?;
            Ok(())
        }
        Err(e) if e.kind() == std::io::ErrorKind::PermissionDenied => {
            tracing::warn!(
                "cannot create {} as this user; 'make install' creates it with the right owner",
                state_dir.display()
            );
            Ok(())
        }
        Err(e) => Err(e.into()),
    }
}

/// Detect the host's private LAN address from the main routing table.
#[allow(clippy::disallowed_methods)] // the CLI may run `ip`; the server crates may not
fn detect_server_ip() -> Result<IpAddr> {
    let output = std::process::Command::new("ip")
        .args(["-4", "route", "show", "default"])
        .output()
        .map_err(|e| Error::Config(format!("could not run 'ip': {e}")))?;
    let text = String::from_utf8_lossy(&output.stdout);
    for line in text.lines() {
        let mut fields = line.split_whitespace();
        while let Some(field) = fields.next() {
            if field == "src" {
                if let Some(addr) = fields.next() {
                    if let Some(ip) = addr.parse::<IpAddr>().ok().filter(|ip| is_lan_address(*ip)) {
                        return Ok(ip);
                    }
                }
            }
        }
    }
    Err(Error::Config(
        "could not detect a private LAN address from the default route; pass --server-ip"
            .to_string(),
    ))
}

/// Return `true` for the addresses a LAN deployment may use.
///
/// The certificate binds this address, so a public or tunnel address would
/// produce a certificate the clients cannot verify. RFC1918 IPv4 addresses and
/// loopback (for a development round and the self-share) are accepted.
const fn is_lan_address(ip: IpAddr) -> bool {
    match ip {
        IpAddr::V4(v4) => v4.is_private() || v4.is_loopback(),
        IpAddr::V6(v6) => v6.is_loopback(),
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::missing_assert_message)]

    use std::net::{Ipv4Addr, Ipv6Addr};

    use super::*;

    #[test]
    fn private_and_loopback_addresses_are_lan_addresses() {
        for ip in [
            Ipv4Addr::new(10, 0, 0, 5),
            Ipv4Addr::new(172, 16, 4, 1),
            Ipv4Addr::new(192, 168, 1, 10),
            Ipv4Addr::LOCALHOST,
        ] {
            assert!(is_lan_address(IpAddr::V4(ip)));
        }
        assert!(is_lan_address(IpAddr::V6(Ipv6Addr::LOCALHOST)));
    }

    #[test]
    fn public_and_cgnat_addresses_are_not_lan_addresses() {
        for ip in [
            Ipv4Addr::new(8, 8, 8, 8),
            Ipv4Addr::new(203, 0, 113, 7),
            Ipv4Addr::new(100, 64, 0, 1),
        ] {
            assert!(!is_lan_address(IpAddr::V4(ip)));
        }
        // Only loopback IPv6 is accepted; a global or unique-local address is
        // not bound to a LAN here.
        assert!(!is_lan_address(IpAddr::V6(Ipv6Addr::new(
            0x2001, 0xdb8, 0, 0, 0, 0, 0, 1
        ))));
    }
}

